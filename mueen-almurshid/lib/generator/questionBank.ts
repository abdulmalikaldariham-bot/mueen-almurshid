/**
 * بنك الأسئلة (500 سؤال) — مصدر الأسئلة في النسخة الأولى.
 *
 * قواعد الصياغة المتّبعة هنا:
 * - أسئلة مفتوحة، قصيرة، غير موجِّهة، ولا تحمل نصيحة أو حكمًا.
 * - السؤال العام (بلا themes) لا يفترض أي معلومة عن المسترشد.
 * - السؤال المرتبط بموضوع (themes) لا يظهر إلا إذا ذُكر الموضوع في وصف الحالة.
 * - الصياغة تصلح لمخاطبة المذكر والمؤنث دون تعديل (تجنّب المضارع المخاطَب
 *   والصفات المذكّرة)، حتى لا يحتاج المرشد إلى تصحيحها.
 *
 * {A} و {B} يُستبدلان بالخيارين المذكورين في الوصف (needsPair).
 *
 * التوزيع: لكل غرض قسم عام، ثم أسئلة الخيارين، ثم أسئلة الموضوعات الاثني عشر.
 * عند الإضافة حافظ على هذا الترتيب، وشغّل فحص التكرار قبل الرفع.
 */

export interface BankItem {
  text: string;
  purpose: Purpose;
  themes?: Theme[];
  needsPair?: boolean;
}

function general(purpose: Purpose, texts: string[]): BankItem[] {
  return texts.map((text) => ({ text, purpose }));
}

function themed(purpose: Purpose, theme: Theme, texts: string[]): BankItem[] {
  return texts.map((text) => ({ text, purpose, themes: [theme] }));
}

function paired(purpose: Purpose, texts: string[]): BankItem[] {
  return texts.map((text) => ({ text, purpose, needsPair: true }));
}

